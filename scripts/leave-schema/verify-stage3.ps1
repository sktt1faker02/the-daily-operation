# Local artifact verification against the previously read-back metadata and
# a fresh native Dataverse solution export. No network or Dataverse writes.
$ErrorActionPreference = 'Stop'
$leaveRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
Set-Location -LiteralPath $leaveRoot
function Assert-LeaveArtifact {
    param([bool]$Condition, [string]$Description)
    if (-not $Condition) { throw "Stage 3 artifact check failed: $Description" }
}
$leaveStage1 = Get-Content -Raw 'docs/leave-schema-verification.json' | ConvertFrom-Json
$leaveStage2 = Get-Content -Raw 'docs/leave-schema-stage2-verification.json' | ConvertFrom-Json
$leavePermissions = Get-Content -Raw 'docs/leave-permissions-verification.json' | ConvertFrom-Json
$leaveConfig = Get-Content -Raw 'power.config.json' | ConvertFrom-Json
Assert-LeaveArtifact ($leaveConfig.environmentId -ceq 'b58b083e-d27d-eabd-a143-2a49dcb9d89a') 'Environment ID'
Assert-LeaveArtifact $leavePermissions.ConfigurationMatchesPlan 'Permission configuration'
$leaveRegistry = Get-Content -Raw '.power/schemas/appschemas/dataSourcesInfo.ts'
$leaveIndex = Get-Content -Raw 'src/generated/index.ts'
$leaveTables = @(); $leaveColumnCount = 0; $leaveChoiceCount = 0; $leaveLookupCount = 0
foreach ($leaveTable in $leaveStage1.Tables) {
    $leaveMeta = $leaveTable.Metadata
    $leaveRegistrations = @($leaveConfig.databaseReferences.'default.cds'.dataSources.PSObject.Properties | Where-Object { $_.Value.logicalName -ceq $leaveMeta.LogicalName })
    Assert-LeaveArtifact ($leaveRegistrations.Count -eq 1) "$($leaveMeta.LogicalName) one registration"
    $leaveRegistration = $leaveRegistrations[0]
    Assert-LeaveArtifact ($leaveRegistration.Value.entitySetName -ceq $leaveMeta.EntitySetName) 'Entity set registration'
    $leaveSchemaPath = ".power/schemas/dataverse/$($leaveRegistration.Name).Schema.json"
    $leaveSchema = Get-Content -Raw -LiteralPath $leaveSchemaPath | ConvertFrom-Json
    $leaveItems = $leaveSchema.schema.items
    Assert-LeaveArtifact ($leaveSchema.name -ceq $leaveMeta.LogicalName) 'Schema logical name'
    Assert-LeaveArtifact ($leaveItems.'x-ms-dataverse-entityset' -ceq $leaveMeta.EntitySetName) 'Schema entity set'
    Assert-LeaveArtifact ($leaveItems.'x-ms-dataverse-primary-id' -ceq $leaveMeta.PrimaryIdAttribute) 'Schema primary ID'
    $leaveStem = $leaveMeta.EntitySetName.Substring(0,1).ToUpperInvariant() + $leaveMeta.EntitySetName.Substring(1)
    $leaveModelPath = "src/generated/models/$($leaveStem)Model.ts"
    $leaveServicePath = "src/generated/services/$($leaveStem)Service.ts"
    $leaveModel = Get-Content -Raw -LiteralPath $leaveModelPath
    $leaveService = Get-Content -Raw -LiteralPath $leaveServicePath
    Assert-LeaveArtifact ($leaveModel.Contains('This file is autogenerated.')) 'Generated model header'
    Assert-LeaveArtifact ($leaveService.Contains("dataSourceName = '$($leaveMeta.EntitySetName)'")) 'Service source name'
    Assert-LeaveArtifact ($leaveService.Contains("Omit<$($leaveStem)Base, '$($leaveMeta.PrimaryIdAttribute)'>")) 'Create/update primary ID omission'
    Assert-LeaveArtifact ($leaveService.Contains('getClient(dataSourcesInfo)')) 'Supported Power Apps client'
    Assert-LeaveArtifact ($leaveIndex.Contains("./models/$($leaveStem)Model") -and $leaveIndex.Contains("./services/$($leaveStem)Service")) 'Generated index exports'
    Assert-LeaveArtifact ($leaveRegistry.Contains('"' + $leaveMeta.EntitySetName + '"')) 'Client registry source'
    $leaveNativeEntity = Join-Path $PSScriptRoot ".work/unpacked-stage3/Entities/$($leaveMeta.SchemaName)/Entity.xml"
    $leaveRepoEntity = "solution/A365_DailyOperations/src/Entities/$($leaveMeta.SchemaName)/Entity.xml"
    Assert-LeaveArtifact ((Get-FileHash -LiteralPath $leaveNativeEntity).Hash -ceq (Get-FileHash -LiteralPath $leaveRepoEntity).Hash) 'Fresh native metadata matches verified solution source'
    $leaveBindings = @()
    foreach ($leaveColumn in $leaveTable.Columns) {
        $leaveProperty = $leaveItems.properties.($leaveColumn.LogicalName)
        Assert-LeaveArtifact ($null -ne $leaveProperty) "$($leaveColumn.LogicalName) schema column"
        Assert-LeaveArtifact ($leaveProperty.'x-ms-schema-name' -ceq $leaveColumn.SchemaName) "$($leaveColumn.LogicalName) schema name"
        Assert-LeaveArtifact ($leaveProperty.'x-ms-dataverse-type' -ceq ($leaveColumn.AttributeType + 'Type')) "$($leaveColumn.LogicalName) type"
        $leaveRequired = $leaveColumn.RequiredLevel.Value -in @('ApplicationRequired','SystemRequired')
        Assert-LeaveArtifact ([bool]$leaveProperty.required -eq $leaveRequired) "$($leaveColumn.LogicalName) required level"
        if ($leaveColumn.MaxLength) { Assert-LeaveArtifact ($leaveProperty.maxLength -eq $leaveColumn.MaxLength) "$($leaveColumn.LogicalName) length" }
        $leaveModelColumn = $leaveColumn.LogicalName
        if ($leaveColumn.AttributeType -eq 'Lookup') {
            $leaveRelationship = @($leaveStage2.Relationships | Where-Object { $_.ReferencingEntity -ceq $leaveMeta.LogicalName -and $_.ReferencingAttribute -ceq $leaveColumn.LogicalName })
            Assert-LeaveArtifact ($leaveRelationship.Count -eq 1) 'Lookup relationship evidence'
            $leaveModelColumn = '"' + $leaveRelationship[0].ReferencingEntityNavigationPropertyName + '@odata.bind"'
            Assert-LeaveArtifact ($leaveModel.Contains('_' + $leaveColumn.LogicalName + '_value?: string;')) 'Read-only lookup GUID representation'
            $leaveBindings += [ordered]@{ Column=$leaveColumn.LogicalName; Binding=$leaveRelationship[0].ReferencingEntityNavigationPropertyName + '@odata.bind'; Target=$leaveRelationship[0].ReferencedEntity; TargetPrimaryId=$leaveRelationship[0].ReferencedAttribute }
            $leaveLookupCount++
        }
        $leaveOptional = if ($leaveRequired) { '' } else { '?' }
        Assert-LeaveArtifact ($leaveModel.Contains($leaveModelColumn + $leaveOptional + ': ')) "$($leaveColumn.LogicalName) typed model required/optional property"
        if ($leaveColumn.AttributeType -eq 'Picklist') {
            $leaveOptions = @($leaveColumn.VerifiedOptionSet.Options)
            Assert-LeaveArtifact ((@($leaveProperty.'x-ms-enum-values') -join ',') -ceq (@($leaveOptions.Value) -join ',')) 'Choice numeric values'
            $leaveExpectedLabels = @($leaveOptions | ForEach-Object { @($_.Label.LocalizedLabels | Where-Object LanguageCode -eq 1033)[0].Label })
            Assert-LeaveArtifact ((@($leaveProperty.enum) -join '|') -ceq ($leaveExpectedLabels -join '|')) 'Choice labels'
            foreach ($leaveOption in $leaveOptions) {
                $leaveLabel = @($leaveOption.Label.LocalizedLabels | Where-Object LanguageCode -eq 1033)[0].Label
                Assert-LeaveArtifact ($leaveModel.Contains("$($leaveOption.Value): '$leaveLabel'")) 'Typed model numeric choice mapping'
            }
            $leaveChoiceCount++
        }
        $leaveColumnCount++
    }
    $leaveTables += [ordered]@{ LogicalName=$leaveMeta.LogicalName; DataSource=$leaveRegistration.Name; EntitySet=$leaveMeta.EntitySetName; PrimaryId=$leaveMeta.PrimaryIdAttribute; Schema=$leaveSchemaPath; Model=$leaveModelPath; Service=$leaveServicePath; SpecifiedColumns=$leaveTable.Columns.Count; Bindings=$leaveBindings; NativeMetadataMatches=$true }
}
Assert-LeaveArtifact ($leaveColumnCount -eq 39 -and $leaveChoiceCount -eq 7 -and $leaveLookupCount -eq 9) 'Coverage counts'
# Existing generated artifacts must remain byte-for-byte unchanged apart from
# the generator-owned shared index/registry and power.config.json additions.
$leaveSnapshot = Join-Path $PSScriptRoot '.work/stage3-before'
$leavePreserved = 0
foreach ($leaveFolder in @('generated','schemas')) {
    $leaveBeforeRoot = Join-Path $leaveSnapshot $leaveFolder
    foreach ($leaveBeforeFile in Get-ChildItem -LiteralPath $leaveBeforeRoot -Recurse -File) {
        $leaveRelative = $leaveBeforeFile.FullName.Substring($leaveBeforeRoot.Length + 1)
        if ($leaveRelative -in @('index.ts','appschemas\dataSourcesInfo.ts')) { continue }
        $leaveTargetRoot = if ($leaveFolder -eq 'generated') { 'src/generated' } else { '.power/schemas' }
        $leaveCurrentPath = Join-Path $leaveTargetRoot $leaveRelative
        Assert-LeaveArtifact ((Get-FileHash -LiteralPath $leaveBeforeFile.FullName).Hash -ceq (Get-FileHash -LiteralPath $leaveCurrentPath).Hash) "Existing artifact preserved: $leaveRelative"
        $leavePreserved++
    }
}
$leaveBeforeConfig = Get-Content -Raw -LiteralPath (Join-Path $leaveSnapshot 'power.config.json') | ConvertFrom-Json
foreach ($leaveOldSource in $leaveBeforeConfig.databaseReferences.'default.cds'.dataSources.PSObject.Properties) {
    Assert-LeaveArtifact (($leaveOldSource.Value | ConvertTo-Json -Compress) -ceq ($leaveConfig.databaseReferences.'default.cds'.dataSources.($leaveOldSource.Name) | ConvertTo-Json -Compress)) 'Existing source registration preserved'
}
$leaveReport = [ordered]@{
    VerifiedAt=[DateTime]::UtcNow.ToString('o'); Environment=$leaveStage1.Environment; Stage=3
    Tables=$leaveTables; SpecifiedColumns=$leaveColumnCount; LocalChoices=$leaveChoiceCount; BusinessLookups=$leaveLookupCount
    ExistingGeneratedArtifactsPreserved=$leavePreserved; PermissionConfigurationMatches=$true
    Method='Supported installed Microsoft CLI generated every source; native export and prior live metadata used for independent read-back comparison.'
    Limitations=@('Generated binding values are strings; later services must validate target entity-set paths and business rules.','Date Only behavior, precision and numeric bounds are server metadata; generated TypeScript does not enforce them.','Effective access through other user/team roles and sharing has not been tested as ordinary accounts.','No Leave screens or business operations, sample records, deployment, import or commit.')
}
[IO.File]::WriteAllText((Join-Path $leaveRoot 'docs/leave-stage3-verification.json'), ($leaveReport | ConvertTo-Json -Depth 15), (New-Object Text.UTF8Encoding($false)))
Write-Host "PASS: 3 data sources; $leaveColumnCount specified columns; $leaveChoiceCount local choices; $leaveLookupCount business bindings; $leavePreserved existing artifacts preserved."
